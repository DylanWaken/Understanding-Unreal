class Drawing:
    def __init__(self, title, description):
        self.labels = []
        self.parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 620" role="img" aria-labelledby="title desc"><title id="title">{escape(title)}</title><desc id="desc">{escape(description)}</desc>',
                      '<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0 0 L10 5 L0 10 Z" fill="context-stroke"/></marker></defs>',
                      f'<rect width="1200" height="620" rx="12" fill="{BG}"/>',
                      '<g font-family="Inter, Segoe UI, Arial, sans-serif">']
        self.text(40, 49, title, 28)
        self.text(40, 588, 'SCHEMATIC · geometry and colors explain a model; this is not an Unreal buffer', 16, MUTED)

    def text(self, x, y, value, size=23, color=FG, anchor='start'):
        self.labels.append(f'<text x="{x:g}" y="{y:g}" font-size="{size}" fill="{color}" text-anchor="{anchor}">{escape(str(value))}</text>')

    def lines(self, x, y, values, color=MUTED, size=21):
        for i, value in enumerate(values): self.text(x,y+i*29,value,size,color)

    def line(self, x1,y1,x2,y2,color=MUTED,width=3,arrow=False,dash=False):
        extra = (' marker-end="url(#arrow)"' if arrow else '') + (' stroke-dasharray="8 7"' if dash else '')
        self.parts.append(f'<path d="M{x1:g} {y1:g}L{x2:g} {y2:g}" stroke="{color}" stroke-width="{width}" fill="none"{extra}/>')

    def path(self, d, color=MUTED, width=3, fill='none', dash=False):
        self.parts.append(f'<path d="{d}" stroke="{color}" stroke-width="{width}" fill="{fill}"'+(' stroke-dasharray="7 7"' if dash else '')+'/>')

    def rect(self,x,y,w,h,color=BLUE,fill='none',radius=5):
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" stroke="{color}" stroke-width="2" fill="{fill}"/>')

    def circle(self,x,y,r,color=BLUE,fill=None):
        self.parts.append(f'<circle cx="{x:g}" cy="{y:g}" r="{r:g}" stroke="{color}" stroke-width="2" fill="{fill or BG}"/>')

    def ellipse(self,x,y,rx,ry,color=BLUE,dash=False):
        self.parts.append(f'<ellipse cx="{x}" cy="{y}" rx="{rx}" ry="{ry}" stroke="{color}" stroke-width="2" fill="none"'+(' stroke-dasharray="7 6"' if dash else '')+'/>')

    def poly(self,points,color=BLUE,fill='none'):
        self.parts.append(f'<polygon points="'+ ' '.join(f'{x:g},{y:g}' for x,y in points)+f'" stroke="{color}" stroke-width="2" fill="{fill}"/>')

    def box(self,x,y,w,h,title,lines=(),color=BLUE):
        self.rect(x,y,w,h,color,'#18283e')
        self.text(x+16,y+34,title,23,color)
        self.lines(x+16,y+68,lines,size=19)

    def grid(self,x,y,cols,rows,cell=28,selected=(),color=MUTED):
        for j in range(rows):
            for i in range(cols): self.rect(x+i*cell,y+j*cell,cell-2,cell-2,color,GOLD if (i,j) in selected else '#18283e',1)

    def atrium(self,x=40,y=160,scale=1):
        # A cross-section, deliberately schematic rather than traced mesh geometry.
        def pt(a,b):return x+a*scale,y+b*scale
        for a,b,c,d in [(0,250,980,250),(0,250,0,0),(980,250,980,0),(0,0,220,0),(760,0,980,0),(0,100,220,100),(760,100,980,100),(220,0,220,250),(760,0,760,250)]:
            self.line(*pt(a,b),*pt(c,d),MUTED,4)
        for a in [90,160,820,890]: self.rect(*pt(a,110),18*scale,140*scale,MUTED,'#293c50')

    def finish(self): return '\n'.join(self.parts+self.labels+['</g></svg>'])+'\n'


