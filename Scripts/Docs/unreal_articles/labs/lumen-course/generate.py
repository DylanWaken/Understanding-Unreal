    for i in range(13):
        recurrence.append(dict(iteration=i,exact_model=[a,b],changed_model=[c,e]))
        a,b=1+.2*b,.3*a;c,e=1+.2*e,.25*c
    # Independent midpoint integrations: half-vector proposal versus the
    # BRDF over incoming solid angle. Both assume wo=n and Li=1.
    ggx_n, alpha, f0 = 20000, .5, .04
    def distribution(mu):
        return alpha**2 / (math.pi * (mu*mu*(alpha**2-1)+1)**2)
    def visibility(mu):
        return 2 / (1 + math.sqrt(1 + alpha**2*(1-mu*mu)/(mu*mu)))
    def fresnel(mu):
        return f0 + (1-f0)*(1-mu)**5
    projected_norm, reflected_integral, sampled_reflection, null_count = 0., 0., 0., 0
    for i in range(ggx_n):
        u = (i+.5)/ggx_n
        projected_norm += 2*math.pi*distribution(u)*u/ggx_n
        h_cos = math.sqrt((1+u)/2)
        reflected_integral += .5*math.pi*distribution(h_cos)*fresnel(h_cos)*visibility(u)/ggx_n
        sampled_h_cos = math.sqrt((1-u)/(1+(alpha*alpha-1)*u))
        incoming_cos = 2*sampled_h_cos*sampled_h_cos-1
